def nm_text(symbols: dict[str, tuple[int, int | None]]) -> str:
    lines = []
    for name, (address, size) in symbols.items():
        if size is None:
            lines.append(f"{address:016x} A {name}")
        else:
            lines.append(f"{address:016x} {size:016x} A {name}")
    return "\n".join(lines) + "\n"


def objdump_text(
    sections: list[tuple[str, int, int, int] | tuple[str, int, int, int, str]]
) -> str:
    lines = ["", "Sections:", "Idx Name Size VMA LMA File off Algn"]
    for index, section in enumerate(sections):
        name, size, vma, lma = section[:4]
        flags = (
            section[4]
            if len(section) == 5
            else "CONTENTS, ALLOC, LOAD, DATA"
        )
        lines.append(
            f"{index:3d} {name:<18} {size:08x} {vma:08x} {lma:08x} "
            f"00010000 2**2"
        )
        lines.append(f"                  {flags}")
    return "\n".join(lines) + "\n"


