def make_report(
    cpu: str,
    symbols: dict[str, tuple[int, int | None]],
    sections: list[tuple[str, int, int, int] | tuple[str, int, int, int, str]],
    *,
    policy: object = None,
) -> dict:
    return resources.assemble_report(
        board_id="proteus",
        cpu=cpu,
        source_commit="3060ccd587",
        profile=resources.parse_profile(PROFILE),
        symbols=resources.parse_nm(nm_text(symbols)),
        sections=resources.parse_objdump_sections(objdump_text(sections)),
        toolchain={
            "id": "arm-none-eabi-g++",
            "version": "arm-none-eabi-g++ test version",
            "sha256": "a" * 64,
        },
        elf_sha256="b" * 64,
        policy_data=policy,
    )


class ParsingTests(unittest.TestCase):
    def test_nm_accepts_sized_and_unsized_symbols(self) -> None:
        parsed = resources.parse_nm(
            "0000000020000000 A __ram0_base__\n"
            "0000000020008000 A __ram0_end__\n"
            "0000000020004000 00000004 D persistentState\n"
        )
        self.assertIsNone(parsed["__ram0_base__"]["size"])
        self.assertEqual(4, parsed["persistentState"]["size"])

    def test_nm_accepts_linker_unknown_types_and_ignores_duplicate_locals(self) -> None:
        parsed = resources.parse_nm(
            "0000000020000020 ? __ram0_base__\n"
            "0000000020020000 ? __ram0_end__\n"
            "000000002001614c ? __ram0_free__\n"
            "0000000020016150 ? __heap_base__\n"
            "0000000020020000 ? __heap_end__\n"
            "00000000100028c0 00000004 D persistentState\n"
            "0000000008057140 00000004 r CSWTCH.1\n"
            "0000000008058140 00000004 r CSWTCH.1\n"
            "0000000008008000 00000004 T __func__\n"
            "0000000008009000 00000004 T __func__\n"
        )
        self.assertEqual(0x20000020, parsed["__ram0_base__"]["address"])
        self.assertIsNone(parsed["__ram0_base__"]["size"])
        self.assertEqual(4, parsed["persistentState"]["size"])
        self.assertNotIn("CSWTCH.1", parsed)
        self.assertNotIn("__func__", parsed)

    def test_nm_rejects_duplicate_relevant_symbols(self) -> None:
        with self.assertRaisesRegex(resources.ExtractionError, "duplicate"):
            resources.parse_nm(
                "0000000020016150 ? __heap_base__\n"
                "0000000020016154 ? __heap_base__\n"
            )

    def test_profile_reads_cylinder_fuel_trim_key_and_sorts_modules(self) -> None:
        profile = resources.parse_profile(PROFILE)
        self.assertEqual(["boost", "fan", "map_averaging"], profile["modules"])
        self.assertEqual(6, profile["cylinder_trim_count"])
        self.assertEqual(["MINIMAL_PINS", "PROTEUS_BMW_M73"], profile["engine_presets"])

    def test_malformed_nm_and_objdump_fail_closed(self) -> None:
        with self.assertRaises(resources.ExtractionError):
            resources.parse_nm("not symbol data\n")
        with self.assertRaises(resources.ExtractionError):
            resources.parse_objdump_sections("not a section table\n")


class ExtractionTests(unittest.TestCase):
    def test_f7_flash_accounting_uses_lma_not_vma(self) -> None:
        report = make_report("ARCH_STM32F7", f7_symbols(), f7_sections())
        self.assertEqual("accepted", report["status"])
        text = next(
            section for section in report["flash_load_sections"] if section["name"] == ".text"
        )
        self.assertEqual(0x00200000, text["vma"])
        self.assertEqual(0x08020000, text["lma"])
        self.assertEqual(0x200, report["initialized_ram_load_bytes"])

    def test_realistic_archived_f7_style_output(self) -> None:
        report = make_report("ARCH_STM32F7", f7_symbols(), f7_sections())
        self.assertEqual("accepted", report["status"])
        self.assertEqual(34180, report["regions"]["flash"]["free_bytes"])
        self.assertEqual(55824, report["regions"]["ram3"]["free_bytes"])
        self.assertEqual(55824, report["heap"]["capacity_bytes"])
        self.assertEqual(32768, report["persistent"]["capacity_bytes"])
        self.assertEqual(31332, report["persistent"]["used_bytes"])
        self.assertEqual(1436, report["persistent"]["free_bytes"])
        self.assertEqual(0, report["regions"]["ram6"]["capacity_bytes"])
        self.assertEqual(0, report["regions"]["ram7"]["capacity_bytes"])
        self.assertFalse(report["hardware_guarantee"])

    def test_h7_reports_linker_limit_but_gates_at_config_boundary(self) -> None:
        report = make_report("ARCH_STM32H7", h7_symbols(), h7_sections())
        flash = report["regions"]["flash"]
        self.assertEqual("accepted", report["status"])
        self.assertEqual(0x08100000, flash["limit"])
        self.assertEqual(0x08120000, flash["linker_limit"])
        self.assertEqual(178404, flash["free_bytes"])

    def test_h7_application_load_crossing_config_is_rejected(self) -> None:
        sections = h7_sections() + [
            (".configuration_like", 0x2000, 0x080FF000, 0x080FF000)
        ]
        report = make_report("ARCH_STM32H7", h7_symbols(), sections)
        self.assertEqual("rejected", report["status"])
        self.assertIn(
            "flash_load_overlaps_config",
            {violation["code"] for violation in report["violations"]},
        )

    def test_h7_ram_aliases_overlap_without_aggregate(self) -> None:
        report = make_report("ARCH_STM32H7", h7_symbols(), h7_sections())
        self.assertIn("ram2", report["regions"]["ram1"]["overlaps"])
        group = next(
            group
            for group in report["ram_alias_groups"]
            if "ram1" in group["regions"]
        )
        self.assertEqual(["ram1", "ram2", "ram3"], group["regions"])
        self.assertIsNone(group["aggregate_bytes"])
        self.assertNotIn("ram_total", report)

    def test_alias_consumption_uses_alloc_sections_and_excludes_heap(self) -> None:
        policy = {
            "schema_version": 1,
            "required_free_bytes": {"ram1": 0x5EB5},
        }
        report = make_report(
            "ARCH_STM32F4", f4_symbols(), f4_sections(), policy=policy
        )
        self.assertEqual("rejected", report["status"])
        self.assertEqual(0x9EB4, report["regions"]["ram0"]["free_bytes"])
        self.assertEqual(0x5EB4, report["regions"]["ram1"]["free_bytes"])
        self.assertEqual(0x1BFE0, report["regions"]["ram1"]["linker_free_bytes"])
        self.assertIn("ram1", report["regions"]["ram0"]["overlaps"])
        self.assertIn(
            "policy_free_below_minimum",
            {violation["code"] for violation in report["violations"]},
        )

    def test_load_only_sections_do_not_mark_ram_consumed(self) -> None:
        sections = f4_sections() + [
            (
                ".load_only_probe",
                0x1000,
                0x2001B000,
                0x0805D000,
                "CONTENTS, LOAD",
            )
        ]
        report = make_report("ARCH_STM32F4", f4_symbols(), sections)
        self.assertEqual(0x5EB4, report["regions"]["ram1"]["free_bytes"])

    def test_f7_persistent_overflow_is_rejected(self) -> None:
        report = make_report("ARCH_STM32F7", f7_symbols(32872), f7_sections())
        self.assertEqual("rejected", report["status"])
        self.assertEqual("rejected", report["persistent"]["status"])
        self.assertLess(report["persistent"]["free_bytes"], 0)

    def test_missing_required_symbols_are_rejected(self) -> None:
        symbols = f7_symbols()
        del symbols["__flash0_free__"]
        del symbols["__ram7_end__"]
        del symbols["persistentState"]
        report = make_report("ARCH_STM32F7", symbols, f7_sections())
        self.assertEqual("rejected", report["status"])
        codes = {violation["code"] for violation in report["violations"]}
        self.assertIn("missing_symbol", codes)
        self.assertIn("missing_ram_symbols", codes)

    def test_missing_expected_heap_region_is_rejected(self) -> None:
        symbols = h7_symbols()
        for suffix in ("base", "end", "free"):
            del symbols[f"__ram0_{suffix}__"]
        report = make_report("ARCH_STM32H7", symbols, h7_sections())
        self.assertEqual("rejected", report["status"])
        self.assertIn(
            "malformed_heap",
            {violation["code"] for violation in report["violations"]},
        )

    def test_negative_ram_capacity_is_rejected(self) -> None:
        symbols = f7_symbols()
        symbols["__ram6_base__"] = (0x1000, None)
        report = make_report("ARCH_STM32F7", symbols, f7_sections())
        self.assertEqual("rejected", report["status"])
        self.assertEqual(
            -0x1000,
            report["regions"]["ram6"]["capacity_bytes"],
        )
        self.assertIn(
            "malformed_ram_symbols",
            {violation["code"] for violation in report["violations"]},
        )

    def test_unsized_persistent_state_is_rejected(self) -> None:
        symbols = f7_symbols()
        symbols["persistentState"] = (0x20010000, None)
        report = make_report("ARCH_STM32F7", symbols, f7_sections())
        self.assertEqual("rejected", report["status"])
        self.assertIn(
            "missing_persistent_size",
            {violation["code"] for violation in report["violations"]},
        )

    def test_policy_minimum_free_and_heap_are_enforced(self) -> None:
        policy = {
            "schema_version": 1,
            "required_free_bytes": {"flash": 40000},
            "minimum_heap_capacity_bytes": 56000,
        }
        report = make_report("ARCH_STM32F7", f7_symbols(), f7_sections(), policy=policy)
        self.assertEqual("rejected", report["status"])
        codes = [violation["code"] for violation in report["violations"]]
        self.assertIn("policy_free_below_minimum", codes)
        self.assertIn("policy_heap_below_minimum", codes)
        self.assertEqual(40000, report["regions"]["flash"]["required_free_bytes"])
        self.assertEqual(56000, report["heap"]["required_capacity_bytes"])

    def test_policy_rejects_unknown_and_negative_entries(self) -> None:
        with self.assertRaises(resources.ExtractionError):
            resources.normalize_policy(
                {
                    "schema_version": 1,
                    "required_free_bytes": {"ram99": 1},
                },
                {"flash", "ram0", "persistent"},
            )
        with self.assertRaises(resources.ExtractionError):
            resources.normalize_policy(
                {
                    "schema_version": 1,
                    "minimum_heap_capacity_bytes": -1,
                },
                {"flash", "ram0", "persistent"},
            )


class ToolchainIdentityTests(unittest.TestCase):
    def _identity(
        self, version: str = "arm-none-eabi-g++ 11.3.1\nCopyright"
    ) -> dict[str, str]:
        with (
            mock.patch.object(resources, "_run_tool", return_value=version),
            mock.patch.object(resources, "sha256_file", return_value="a" * 64),
        ):
            return resources.toolchain_identity(Path("/tools/arm-none-eabi-g++"))

    def test_identity_hashes_compiler_binary_and_version(self) -> None:
        identity = self._identity()
        self.assertEqual(64, len(identity["id"]))
        self.assertNotEqual("arm-none-eabi-g++", identity["id"])
        self.assertEqual("arm-none-eabi-g++ 11.3.1", identity["version"])
        self.assertEqual("a" * 64, identity["sha256"])
        with (
            mock.patch.object(
                resources, "_run_tool", return_value="arm-none-eabi-g++ 11.3.1\n"
            ),
            mock.patch.object(resources, "sha256_file", return_value="a" * 64),
        ):
            self.assertEqual(
                identity,
                resources.toolchain_identity(Path("/other/path/arm-none-eabi-g++")),
            )

    def test_different_binary_or_version_changes_identity(self) -> None:
        baseline = self._identity()
        with (
            mock.patch.object(
                resources, "_run_tool", return_value="arm-none-eabi-g++ 11.3.1\n"
            ),
            mock.patch.object(resources, "sha256_file", return_value="b" * 64),
        ):
            changed_binary = resources.toolchain_identity(
                Path("/tools/arm-none-eabi-g++")
            )
        with (
            mock.patch.object(
                resources, "_run_tool", return_value="arm-none-eabi-g++ 12.2.0\n"
            ),
            mock.patch.object(resources, "sha256_file", return_value="a" * 64),
        ):
            changed_version = resources.toolchain_identity(
                Path("/tools/arm-none-eabi-g++")
            )
        self.assertNotEqual(baseline["id"], changed_binary["id"])
        self.assertNotEqual(baseline["id"], changed_version["id"])

    def test_empty_version_is_rejected(self) -> None:
        with (
            mock.patch.object(resources, "_run_tool", return_value="\n"),
            mock.patch.object(resources, "sha256_file", return_value="a" * 64),
        ):
            with self.assertRaisesRegex(resources.ExtractionError, "no identity"):
                resources.toolchain_identity(Path("/tools/arm-none-eabi-g++"))


class CliTests(unittest.TestCase):
    def test_nonzero_exit_and_json_diagnostic_on_rejection(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary)
            output = directory / "report.json"
            code = resources.main(
                [
                    "extract",
                    "--elf",
                    str(directory / "missing.elf"),
                    "--profile",
                    str(directory / "missing-profile.txt"),
                    "--board",
                    "proteus",
                    "--cpu",
                    "ARCH_STM32F7",
                    "--source-commit",
                    "3060ccd587",
                    "--output",
                    str(output),
                    "--root",
                    str(directory),
                    "--nm",
                    str(directory / "missing-nm"),
                    "--objdump",
                    str(directory / "missing-objdump"),
                    "--compiler",
                    str(directory / "missing-compiler"),
                ]
            )
            self.assertNotEqual(0, code)
            report = json.loads(output.read_text(encoding="utf-8"))
            self.assertEqual("rejected", report["status"])
            self.assertEqual("extraction_failed", report["violations"][0]["code"])


