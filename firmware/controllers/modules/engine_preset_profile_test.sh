#!/bin/bash

set -euo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
tool="$script_dir/engine_preset_profile.sh"
dispatch_source="$script_dir/../algo/engine_configuration.cpp"
enum_source="$script_dir/../algo/engine_types.h"
temporary=$(mktemp -d)
trap 'rm -rf "$temporary"' EXIT

selection_file="$temporary/selection"
default_file="$temporary/default"
header="$temporary/generated.h"
metadata="$temporary/generated.mk"
ts_definitions="$temporary/generated.txt"

fail() {
	printf 'FAIL: %s\n' "$*" >&2
	exit 1
}

render() {
	local origin=$1
	local selection=$2
	local ve_rpm=$3
	local blend_size=$4
	local default_engine=$5

	printf '%s' "$selection" > "$selection_file"
	printf '%s\n' "$default_engine" > "$default_file"
	"$tool" render \
		--header "$header" \
		--metadata "$metadata" \
		--ts-definitions "$ts_definitions" \
		--dispatch-source "$dispatch_source" \
		--enum-source "$enum_source" \
		--selection-file "$selection_file" \
		--selection-origin "$origin" \
		--default-file "$default_file" \
		--ve-rpm "$ve_rpm" \
		--blend-size "$blend_size" >/dev/null
}

expect_error() {
	local expected=$1
	local origin=$2
	local selection=$3
	local ve_rpm=$4
	local blend_size=$5
	local default_engine=$6
	local output

	printf '%s' "$selection" > "$selection_file"
	printf '%s\n' "$default_engine" > "$default_file"
	if output=$("$tool" render \
		--header "$header" \
		--metadata "$metadata" \
		--ts-definitions "$ts_definitions" \
		--dispatch-source "$dispatch_source" \
		--enum-source "$enum_source" \
		--selection-file "$selection_file" \
		--selection-origin "$origin" \
		--default-file "$default_file" \
		--ve-rpm "$ve_rpm" \
		--blend-size "$blend_size" 2>&1); then
		fail "expected selector failure containing '$expected'"
	fi
	[[ "$output" == *"$expected"* ]] || fail "expected '$expected', got '$output'"
}

expect_line() {
	local line=$1
	grep -Fqx "$line" "$metadata" || fail "missing metadata line: $line"
}

expect_header() {
	local line=$1
	grep -Fqx "$line" "$header" || fail "missing generated header line: $line"
}

expect_ts_header() {
	local first_line
	IFS= read -r first_line < "$ts_definitions"
	[[ "$first_line" == '! Generated by engine_preset_profile.sh. Do not edit.' ]] ||
		fail "TunerStudio definitions do not start with a valid '!' comment: $first_line"
}

# Legacy shape: omitted selector means all presets, preserving enum IDs and defaults.
render undefined '' 16 8 HELLEN_NB2
expect_line 'MODULE_ENGINE_PRESET_PROFILE_MODE := default_all'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_EXPANDED := 0'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_DEFAULT_ENGINE_TYPE_ENABLED := 1'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_FORD_ESCORT_GT 1'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_HELLEN_NB2 1'

# Omitted selector in either expanded dimension means no engine-specific presets.
render undefined '' 32 8 HELLEN_NB2
expect_line 'MODULE_ENGINE_PRESET_PROFILE_MODE := default_none'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_EXPANDED := 1'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_SELECTED := MINIMAL_PINS'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_DEFAULT_ENGINE_TYPE_ENABLED := 0'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_HELLEN_NB2 0'

render undefined '' 16 16 HELLEN_NB2
expect_line 'MODULE_ENGINE_PRESET_PROFILE_MODE := default_none'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_DEFAULT_ENGINE_TYPE_ENABLED := 0'

# Explicit none is valid at every shape and excludes every preset.
render 'command line' none 32 16 HELLEN_NB2
expect_line 'MODULE_ENGINE_PRESET_PROFILE_MODE := explicit_none'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_SELECTED := MINIMAL_PINS'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_HELLEN_NB2 0'
expect_ts_header

# Exact symbols resolve in dispatch order and are the only enabled presets.
render 'command line' 'HELLEN_NB2 FORD_ESCORT_GT' 16 8 HELLEN_NB2
expect_line 'MODULE_ENGINE_PRESET_PROFILE_MODE := explicit'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_SELECTED := MINIMAL_PINS HELLEN_NB2 FORD_ESCORT_GT'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_DEFAULT_ENGINE_TYPE_ENABLED := 1'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_FORD_ESCORT_GT 1'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_HELLEN_NB2 1'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_HELLEN_NA6 0'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_MINIMAL_PINS 1'

# MINIMAL_PINS is a hardware-only selection and remains valid with expanded dimensions.
render 'command line' MINIMAL_PINS 32 16 FORD_ESCORT_GT
expect_line 'MODULE_ENGINE_PRESET_PROFILE_SELECTED := MINIMAL_PINS'
expect_line 'MODULE_ENGINE_PRESET_PROFILE_DEFAULT_ENGINE_TYPE_ENABLED := 0'
expect_header '#define FOME_ENGINE_PRESET_ENABLED_MINIMAL_PINS 1'

expect_error 'explicitly empty' 'file' '' 16 8 MINIMAL_PINS
expect_error "cannot mix 'all'" 'command line' 'all none' 16 8 MINIMAL_PINS
expect_error 'unknown FOME_ENGINE_PRESETS' 'command line' 'NOT_AN_ENGINE' 16 8 MINIMAL_PINS
expect_error 'unsupported engine preset' 'command line' 'ET_UNUSED_1' 16 8 MINIMAL_PINS
expect_error 'cannot include literal engine presets' 'command line' all 32 8 MINIMAL_PINS
expect_error 'cannot include literal engine presets' 'command line' HELLEN_NB2 16 16 MINIMAL_PINS
expect_error 'FOME_VE_RPM_COUNT_RESOLVED must be 16 or 32' 'command line' none 24 8 MINIMAL_PINS
expect_error 'FOME_AIRMASS_BLEND_SIZE_RESOLVED must be 8 or 16' 'command line' none 16 12 MINIMAL_PINS

# Validate the Make include contract without compiling or invoking a board build.
project_dir=$(cd "$script_dir/../.." && pwd)
make_output=$("make" --no-print-directory -f - \
	PROJECT_DIR="$project_dir" \
	MODULE_ROOT="$project_dir/controllers/modules" \
	FOME_VE_RPM_COUNT_RESOLVED=16 \
	FOME_AIRMASS_BLEND_SIZE_RESOLVED=8 <<'MAKE'
DDEFS := -DDEFAULT_ENGINE_TYPE=HELLEN_NB2
include $(PROJECT_DIR)/controllers/modules/engine_preset_profile.mk
print-engine-preset-profile:
	@printf '%s\n' '$(MODULE_ENGINE_PRESET_PROFILE_MODE)|$(MODULE_ENGINE_PRESET_PROFILE_SELECTED)|$(MODULE_ENGINE_PRESET_PROFILE_DEFAULT_ENGINE_TYPE_ENABLED)|$(filter -DFOME_ENGINE_PRESET_PROFILE_CONFIGURED=1,$(DDEFS))|$(MODULE_ENGINE_PRESET_PROFILE_TS_DEFINITIONS)'
MAKE
)
IFS='|' read -r make_mode make_selected make_default_enabled make_feature_define make_ts_definitions <<< "$make_output"
[[ "$make_mode" == default_all ]] || fail "Make integration did not default to all presets"
[[ " $make_selected " == *' HELLEN_NB2 '* ]] || fail "Make integration did not include the board default"
[[ "$make_default_enabled" == 1 ]] ||
	fail "Make integration did not preserve the board default or C++ feature define: $make_output"
[[ "$make_feature_define" == -DFOME_ENGINE_PRESET_PROFILE_CONFIGURED=1 ]] ||
	fail "Make integration did not add the generated-header feature define: $make_output"
[[ "$make_ts_definitions" == */engine_preset_profile_ts_definitions.txt ]] ||
	fail "Make integration did not expose the TunerStudio definitions path: $make_output"

make_output=$("make" --no-print-directory -f - \
	PROJECT_DIR="$project_dir" \
	MODULE_ROOT="$project_dir/controllers/modules" \
	FOME_VE_RPM_COUNT_RESOLVED=32 \
	FOME_AIRMASS_BLEND_SIZE_RESOLVED=16 \
	FOME_ENGINE_PRESETS=none <<'MAKE'
DDEFS := -DDEFAULT_ENGINE_TYPE=HELLEN_NB2
include $(PROJECT_DIR)/controllers/modules/engine_preset_profile.mk
print-engine-preset-profile:
	@printf '%s\n' '$(MODULE_ENGINE_PRESET_PROFILE_MODE)|$(MODULE_ENGINE_PRESET_PROFILE_SELECTED)|$(MODULE_ENGINE_PRESET_PROFILE_DEFAULT_ENGINE_TYPE_ENABLED)'
MAKE
)
[[ "$make_output" == 'explicit_none|MINIMAL_PINS|0' ]] ||
	fail "Make integration did not accept explicit none with expanded dimensions: $make_output"

if make_output=$("make" --no-print-directory -f - \
	PROJECT_DIR="$project_dir" \
	MODULE_ROOT="$project_dir/controllers/modules" \
	FOME_VE_RPM_COUNT_RESOLVED=32 \
	FOME_AIRMASS_BLEND_SIZE_RESOLVED=8 \
	FOME_ENGINE_PRESETS=all <<'MAKE' 2>&1
DDEFS := -DDEFAULT_ENGINE_TYPE=MINIMAL_PINS
include $(PROJECT_DIR)/controllers/modules/engine_preset_profile.mk
print-engine-preset-profile:
	@:
MAKE
); then
	fail "Make integration accepted explicit all with expanded dimensions"
fi
[[ "$make_output" == *'cannot include literal engine presets'* ]] ||
	fail "Make integration returned the wrong expanded-mode error: $make_output"

# Leave source-tree generated artifacts in the legacy all-presets shape.
"make" --no-print-directory -f - \
	PROJECT_DIR="$project_dir" \
	MODULE_ROOT="$project_dir/controllers/modules" \
	FOME_VE_RPM_COUNT_RESOLVED=16 \
	FOME_AIRMASS_BLEND_SIZE_RESOLVED=8 <<'MAKE' >/dev/null
DDEFS := -DDEFAULT_ENGINE_TYPE=MINIMAL_PINS
include $(PROJECT_DIR)/controllers/modules/engine_preset_profile.mk
all:
	@:
MAKE

printf 'PASS: engine preset profile selector\n'
